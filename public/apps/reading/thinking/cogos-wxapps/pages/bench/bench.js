  data: { wbsteps: WBSTEPS, domains: DOMAINS, di: 0, step: 0, d: DOMAINS[0] },
  onDomain(e) {
    const i = e.currentTarget.dataset.i;
    this.setData({ di: i, step: 0, d: DOMAINS[i] });
    try { wx.vibrateShort({ type: 'light' }); } catch (err) {}
  },
  onStep() {
    if (this.data.step >= 5) return;
    const step = this.data.step + 1;
    this.setData({ step });
    try { wx.vibrateShort({ type: step === 4 ? 'medium' : 'light' }); } catch (err) {}
    if (step === 4) wx.showToast({ title: '链条点亮 · 相变序列显影', icon: 'none' });
  },
