const atlas = document.querySelector('.sa-atlas');
const tip = document.getElementById('sa-tip');

function moveTip(event) {
  if (!tip) return;
  const pad = 16;
  let x = event.clientX + 14;
  let y = event.clientY + 18;
  const width = tip.offsetWidth;
  const height = tip.offsetHeight;
  if (x + width + pad > window.innerWidth) x = event.clientX - width - 14;
  if (y + height + pad > window.innerHeight) y = event.clientY - height - 14;
  tip.style.left = `${x}px`;
  tip.style.top = `${y}px`;
}

function toggleDirection(dir) {
  const svg = dir.closest('svg');
  if (!svg) return;
  const group = svg.querySelector(`g.sector[data-dir="${dir.dataset.dir}"]`);
  if (!group) return;
  const active = group.classList.contains('hot') && svg.classList.contains('dim');
  svg.classList.toggle('dim', !active);
  svg.querySelectorAll('g.sector').forEach((item) => item.classList.remove('hot'));
  if (!active) group.classList.add('hot');
}

if (atlas && tip) {
  atlas.addEventListener('pointerover', (event) => {
    const target = event.target;
    if (!(target instanceof Element)) return;

    const point = target.closest('.pt,.gap');
    if (point) {
      tip.textContent = point.getAttribute('data-tip') || '';
      tip.style.opacity = '1';
      moveTip(event);
      return;
    }

    const dir = target.closest('.dir');
    if (dir) {
      const svg = dir.closest('svg');
      if (!svg) return;
      svg.classList.add('dim');
      svg.querySelectorAll('g.sector').forEach((group) => {
        group.classList.toggle('hot', group.getAttribute('data-dir') === dir.getAttribute('data-dir'));
      });
    }
  });

  atlas.addEventListener('pointermove', (event) => {
    const target = event.target;
    if (tip.style.opacity === '1' && target instanceof Element && target.closest('.pt,.gap')) {
      moveTip(event);
    }
  });

  atlas.addEventListener('pointerout', (event) => {
    const target = event.target;
    if (!(target instanceof Element)) return;
    if (target.closest('.pt,.gap')) tip.style.opacity = '0';

    const dir = target.closest('.dir');
    if (dir) {
      const svg = dir.closest('svg');
      if (!svg) return;
      svg.classList.remove('dim');
      svg.querySelectorAll('g.sector.hot').forEach((group) => group.classList.remove('hot'));
    }
  });

  atlas.addEventListener('click', (event) => {
    const target = event.target;
    if (!(target instanceof Element)) return;
    const dir = target.closest('.dir');
    if (dir) toggleDirection(dir);
  });

  atlas.addEventListener('keydown', (event) => {
    const target = event.target;
    if (!(target instanceof Element)) return;
    const dir = target.closest('.dir');
    if (dir && (event.key === 'Enter' || event.key === ' ')) {
      event.preventDefault();
      toggleDirection(dir);
    }
  });
}

