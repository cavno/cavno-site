  svg += `<circle cx="${C}" cy="${C}" r="72" fill="var(--parch-deep)" stroke="rgba(58,50,38,.55)" stroke-width="1.6"/>`
    + `<circle cx="${C}" cy="${C}" r="63" fill="none" stroke="rgba(58,50,38,.35)" stroke-width="1" stroke-dasharray="2 4"/>`
    + `<text class="hubregion" x="${C}" y="${C - 24}" text-anchor="middle">${esc(reg.region)}</text>`
